CREATE TABLE telemetry_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(128) NOT NULL,
    metric VARCHAR(64) NOT NULL,
    sample_value DOUBLE PRECISION NOT NULL,
    t_device TIMESTAMP WITH TIME ZONE NOT NULL,
    t_ingress TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'VALIDATED',
    correlation_id VARCHAR(128) NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_telemetry_records_status CHECK (status IN ('VALIDATED', 'VALIDATION_FAILED'))
);

CREATE TABLE telemetry_event_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT NOT NULL,
    revision_number INTEGER NOT NULL,
    sample_value DOUBLE PRECISION NOT NULL,
    t_device TIMESTAMP WITH TIME ZONE NOT NULL,
    t_ingress TIMESTAMP WITH TIME ZONE NOT NULL,
    correlation_id VARCHAR(128) NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_telemetry_event_revisions_record FOREIGN KEY (record_id) REFERENCES telemetry_records (id),
    CONSTRAINT uq_telemetry_event_revisions_record_revision UNIQUE (record_id, revision_number),
    CONSTRAINT ck_telemetry_event_revisions_number CHECK (revision_number >= 1)
);
