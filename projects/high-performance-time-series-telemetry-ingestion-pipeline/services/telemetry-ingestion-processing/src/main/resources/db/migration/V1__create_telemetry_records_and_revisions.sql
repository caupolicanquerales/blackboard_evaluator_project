CREATE TABLE IF NOT EXISTS raw_telemetry_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(128) NOT NULL,
    metric VARCHAR(64) NOT NULL,
    t_device TIMESTAMP WITH TIME ZONE NOT NULL,
    t_ingress TIMESTAMP WITH TIME ZONE NOT NULL,
    sample_value DOUBLE PRECISION NOT NULL,
    validation_status VARCHAR(32) NOT NULL,
    payload VARCHAR(8000) NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_raw_telemetry_records_identity UNIQUE (device_id, metric, t_device),
    CONSTRAINT ck_raw_telemetry_records_status CHECK (validation_status IN ('VALID', 'VALIDATION_FAILED'))
);

CREATE TABLE IF NOT EXISTS event_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_record_id BIGINT NOT NULL,
    device_id VARCHAR(128) NOT NULL,
    metric VARCHAR(64) NOT NULL,
    t_device TIMESTAMP WITH TIME ZONE NOT NULL,
    revision_number INTEGER NOT NULL,
    sample_value DOUBLE PRECISION NOT NULL,
    validation_status VARCHAR(32) NOT NULL,
    reason VARCHAR(32) NOT NULL,
    t_ingress TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_event_revisions_raw_record FOREIGN KEY (raw_record_id) REFERENCES raw_telemetry_records (id),
    CONSTRAINT uq_event_revisions_identity_revision UNIQUE (device_id, metric, t_device, revision_number),
    CONSTRAINT ck_event_revisions_revision_number CHECK (revision_number >= 1),
    CONSTRAINT ck_event_revisions_status CHECK (validation_status IN ('VALID', 'VALIDATION_FAILED')),
    CONSTRAINT ck_event_revisions_reason CHECK (reason IN ('correction', 'backfill', 'late'))
);

CREATE INDEX IF NOT EXISTS ix_event_revisions_raw_record_id ON event_revisions (raw_record_id);
