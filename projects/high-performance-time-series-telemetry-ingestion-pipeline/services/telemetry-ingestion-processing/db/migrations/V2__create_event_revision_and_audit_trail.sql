CREATE TABLE event_revision (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id   BIGINT       NOT NULL,
    reason      VARCHAR(32)  NOT NULL,
    value       DOUBLE PRECISION NOT NULL,
    t_ingress   TIMESTAMP    NOT NULL,
    revision_no INT          NOT NULL,
    CONSTRAINT fk_event_revision_sample FOREIGN KEY (sample_id) REFERENCES telemetry_sample (id),
    CONSTRAINT uq_event_revision_no UNIQUE (sample_id, revision_no)
);

CREATE TABLE audit_trail (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor          VARCHAR(128) NOT NULL,
    action         VARCHAR(32)  NOT NULL,
    outcome        VARCHAR(32)  NOT NULL,
    occurred_at    TIMESTAMP    NOT NULL,
    correlation_id VARCHAR(128) NOT NULL
);

CREATE INDEX ix_audit_trail_correlation ON audit_trail (correlation_id);
