CREATE TABLE telemetry_sample (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id         VARCHAR(128) NOT NULL,
    metric            VARCHAR(64)  NOT NULL,
    t_device          TIMESTAMP    NOT NULL,
    t_ingress         TIMESTAMP    NOT NULL,
    value             DOUBLE PRECISION NOT NULL,
    validation_status VARCHAR(32)  NOT NULL,
    CONSTRAINT uq_telemetry_sample_identity UNIQUE (device_id, metric, t_device)
);

CREATE INDEX ix_telemetry_sample_range ON telemetry_sample (device_id, metric, t_device);
